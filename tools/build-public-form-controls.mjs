import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSync } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'app/src/core/public-form-controls.generated.ts');
const bundle = entry => buildSync({
  entryPoints: [join(root, entry)],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2017',
  minify: true,
  legalComments: 'none',
}).outputFiles[0].text.trim();

const select = `<script>\n${bundle('app/src/runtime/public-select.ts')}\n</script>`;
const date = `<script>\n${bundle('app/src/runtime/public-date.ts')}\n</script>`;
const source = `/* GENERATED by tools/build-public-form-controls.mjs. Do not edit. */\n`
  + `export const PUBLIC_SELECT_JS = ${JSON.stringify(select)};\n`
  + `export const PUBLIC_DATE_JS = ${JSON.stringify(date)};\n`;
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, source);
console.log(`Public form control runtimes written to ${output}`);
