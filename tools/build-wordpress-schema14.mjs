import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// Pin the exporter and its dependency lock to the verified schema 14 staging release.
const revision = 'a1b242f0146e33c3db977c3cf51c1a10769c6c22';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = mkdtempSync(join(tmpdir(), 'pagecraft-wordpress-schema14-'));
const output = resolve(root, 'server/src/generated/wordpress-schema14.cjs');

try {
  const archive = execFileSync('git', [
    'archive', revision, 'app/src', 'server/src', 'shared', 'supabase/functions/pagecraft-db/plan-entitlements.ts',
    'package.json', 'package-lock.json', 'server/package.json', 'packages/editor/package.json',
  ], { cwd: root, maxBuffer: 32 * 1024 * 1024 });
  execFileSync('tar', ['-xf', '-', '-C', source], { input: archive });
  execFileSync('npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: source, stdio: 'inherit' });

  const { outputFiles } = await build({
    absWorkingDir: source,
    stdin: {
      contents: "export { createPagePackage, createSitePackage, portableAssetIds } from './server/src/portable-packages.ts';",
      resolveDir: source,
    },
    bundle: true,
    platform: 'node',
    target: 'node24',
    format: 'cjs',
    minify: true,
    legalComments: 'eof',
    banner: { js: `// Generated by tools/build-wordpress-schema14.mjs from Pagecraft ${revision}.` },
    write: false,
  });
  mkdirSync(resolve(root, 'server/src/generated'), { recursive: true });
  writeFileSync(output, outputFiles[0].contents);
} finally {
  rmSync(source, { recursive: true, force: true });
}
